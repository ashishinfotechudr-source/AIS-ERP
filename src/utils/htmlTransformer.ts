export interface HtmlTransformOptions {
  apiEndpoint?: string;
  appTitle?: string;
}

const DEFAULT_API_ENDPOINT = 'api/index.php';

export function transformIndexHtml(
  rawHtml: string,
  options: HtmlTransformOptions = {}
): string {
  const apiEndpoint = (options.apiEndpoint || DEFAULT_API_ENDPOINT).trim() || DEFAULT_API_ENDPOINT;
  const appTitle = (options.appTitle || '').trim();

  let html = rawHtml;

  // 1. Replace IN_GAS detection and internal URL constant so app boots directly on PHP/HTTP host
  const targetGasConst =
    'const IN_GAS = typeof google != "undefined" && !!(google.script && google.script.run), GAS_INTERNAL_URL = "gas://internal"';
  if (!html.includes(targetGasConst)) {
    throw new Error('Could not locate IN_GAS constant in Index.html template.');
  }
  html = html.replace(
    targetGasConst,
    `const IN_GAS = true, GAS_INTERNAL_URL = "api/sync.php", PHP_API_ENDPOINT = ${JSON.stringify(apiEndpoint)}`
  );

  // 2. Replace gsCallFor Google Apps Script RPC transport with HTTP POST JSON fetch bridge
  const gsCallForRegex =
    /function gsCallFor\(co, fn, \.\.\.args\)\s*\{\s*return new Promise\(\(resolve, reject\) => \{[\s\S]*?\}\);\s*\}/;
  if (!gsCallForRegex.test(html)) {
    throw new Error('Could not locate gsCallFor RPC dispatcher in Index.html template.');
  }
  const httpBridgeFn = `function gsCallFor(co, fn, ...args) {
  return (async () => {
    const tok = getToken();
    const tokenArg = NO_TOKEN_FNS.has(fn) ? "" : (co && tok ? tok + "~" + co : tok);
    const headers = { "Content-Type": "application/json", "X-Requested-With": "XMLHttpRequest" };
    if (tok) headers["Authorization"] = "Bearer " + tok;
    let resp;
    try {
      resp = await fetch(PHP_API_ENDPOINT, {
        method: "POST",
        headers,
        body: JSON.stringify({ fn, co: co || "", token: tokenArg, args })
      });
    } catch (netErr) {
      throw new Error("Could not reach the PHP backend (" + (netErr && netErr.message ? netErr.message : "network error") + ").");
    }
    let payload;
    try {
      payload = await resp.json();
    } catch {
      throw new Error("Unexpected response from server (HTTP " + resp.status + "). Ensure PHP & PDO MySQL are running.");
    }
    if (!resp.ok || !payload || payload.ok === false) {
      const raw = String((payload && payload.error) || ("HTTP " + resp.status));
      const m = raw.match(/(AUTH|PERM):\\s*(.*)$/s);
      const e = new Error(m ? m[2] : raw.replace(/^Error:\\s*/, ""));
      if (m) e.code = m[1];
      if (e.code === "AUTH" && !QUIET_AUTH_FNS.has(fn)) handleAuthLost(e.message);
      throw e;
    }
    return payload.data;
  })();
}`;
  html = html.replace(gsCallForRegex, httpBridgeFn);

  // 3. Update first-time Setup Code hints from Apps Script editor log -> PHP install.php
  html = html.replace(
    'setError("Enter the setup code shown in the Apps Script execution log.");',
    'setError("Enter the 8-character setup code generated by install.php.");'
  );
  html = html.replace(
    '/* @__PURE__ */ React.createElement("span", { className: "hint" }, "run ", /* @__PURE__ */ React.createElement("b", null, "setup"), " in the Apps Script editor, then read it in the execution log")',
    '/* @__PURE__ */ React.createElement("span", { className: "hint" }, "shown after running ", /* @__PURE__ */ React.createElement("b", null, "install.php"), " (or in app_settings)")'
  );

  // 4. Update copy that referenced Google Apps Script link / Drive storage wording
  html = html.replace(
    'This app now runs only from its Google Apps Script web app link, where sign-in and access rights are enforced on the server. Open the deployed Web app URL.',
    'Connecting to PHP API backend...'
  );
  html = html.replace(
    'Index.html was pasted completely.',
    'index.html was uploaded completely.'
  );
  html = html.replace(
    'Vendor Register Apps Script backend is live.',
    'Vendor Register PHP/MySQL backend is live.'
  );

  // 5. Optionally customize HTML <title>
  if (appTitle) {
    const safeTitle = appTitle
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;');
    html = html.replace(/<title>[\s\S]*?<\/title>/, `<title>${safeTitle}</title>`);
  }

  // 6. Inject self-hosted metadata tag
  if (!html.includes('name="app-runtime"')) {
    html = html.replace(
      '<meta name="viewport" content="width=device-width, initial-scale=1.0">',
      '<meta name="viewport" content="width=device-width, initial-scale=1.0">\n<meta name="app-runtime" content="php-mysql-selfhosted">'
    );
  }

  return html;
}
